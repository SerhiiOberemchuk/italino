/**
 * Колір-зразок для назви кольору з CRM (українською). Потрібен лише для
 * кружечків у картці товару; точний відтінок продавець бачить на фото.
 */
const SWATCHES: [RegExp, string][] = [
  [/чорн/, "#14110f"],
  [/біл/, "#ffffff"],
  [/бордо/, "#7a1f2b"],
  [/червон|іржав/, "#e0332a"],
  [/темно-син|нічн|navy/, "#1b2a4a"],
  [/яскраво-син|royal|роял/, "#2456d6"],
  [/світло-блакит/, "#bfe0ff"],
  [/блакит|небесн/, "#7db4f5"],
  [/син/, "#1e3a8a"],
  [/темно-зелен/, "#1f5e3a"],
  [/смарагд/, "#0f9d6e"],
  [/петрол/, "#1f6f7a"],
  [/м.ятн|мятн/, "#a7f3d0"],
  [/матча/, "#9dbf6a"],
  [/яблучн|лайм/, "#a3e635"],
  [/зелен/, "#2f9e44"],
  [/помаранч|оранж/, "#f97316"],
  [/жовт/, "#facc15"],
  [/фукс/, "#d6289a"],
  [/рожев/, "#f472b6"],
  [/слив/, "#5b2a86"],
  [/фіолет|бузк/, "#7c3aed"],
  [/коричн/, "#7c4a2d"],
  [/натур|беж|крем/, "#e8dcc5"],
  [/сріб/, "#c0c0c0"],
  [/сір/, "#8e8e8e"],
  [/прозор/, "#e5f0ff"],
];

export function swatchColor(name: string): string {
  const lower = name.toLowerCase();
  for (const [pattern, hex] of SWATCHES) {
    if (pattern.test(lower)) return hex;
  }
  return "#d4cfc7";
}
